#!/usr/bin/env node
// Range/ETag test server for the native download engine (DL-N). Usage: node scripts/download-test-server.mjs --help
import { Buffer } from 'node:buffer';
import { createCipheriv, createHash } from 'node:crypto';
import { createReadStream, readdirSync, readFileSync, statSync } from 'node:fs';
import { createServer } from 'node:http';
import { createServer as createTlsServer } from 'node:https';
import { resolve } from 'node:path';
import { parseArgs } from 'node:util';

const HELP = `Range-capable HTTP server for download-engine tests.

  node scripts/download-test-server.mjs [--port 39320] [--media <dir>] [--rate <bytes/s>]
      [--https-port 39443 --tls-cert <pem> --tls-key <pem>]   same routes over TLS (redirect downgrade checks)
  node scripts/download-test-server.mjs sha256 <size> <name> [variant]

Files
  GET|HEAD /f/<size>/<name>     generated bytes (AES-CTR keystream, position dependent), size like 2560m, 3g, 100k
  GET|HEAD /media/<file>        real files from --media (e.g. Dev World media for playback tests)
  Both: Accept-Ranges, Range (bytes=a-, bytes=a-b), strong ETag, If-Range, 206/416.
  Query on a file URL: ?rate=<bytes/s> (per response throttle, overrides the global one).

Knobs (GET, query parameters, combine freely)
  /admin/config?rate=&resetAfter=&resetCount=&failStatus=&failCount=&latencyMs=&stallAfter=&stallMs=&stallCount=&rangeShift=&rangeShiftCount=
      rate        bytes/s per response (0 = unlimited)
      stallAfter  stop sending (socket stays open) after this many body bytes for stallMs, stallCount responses
      rangeShift  answer a Range request from start+shift with a matching Content-Range (a wrong start), rangeShiftCount times
      resetAfter  destroy the socket after this many body bytes (per response)
      resetCount  how many responses get reset (default unlimited while resetAfter is set)
      failStatus  answer file requests with this status, failCount times (e.g. 503 to mimic a restart)
  /admin/fail?name=<substring>&status=<code>&count=<n>&retryAfter=<s|date:s|none>&method=<any|GET|HEAD>
      per-file rule, e.g. 429 with Retry-After 40 s for one file only; /admin/reset clears rules
  /redirect?to=<url>[&status=307]   redirect (cross-origin header checks); /capture answers the request headers as JSON
  /admin/variant?name=<name>&variant=<v>   switch the bytes and ETag of a generated file (validator change)
  /admin/reset                             clear all knobs and variants
  /admin/log                               last 300 requests as JSON
  /admin/sha256?path=/f/2560m/movie.bin    sha256 + size of a file as currently served
`;

const { values: opts, positionals } = parseArgs({
  allowPositionals: true,
  options: {
    port: { type: 'string', default: '39320' },
    host: { type: 'string', default: '0.0.0.0' },
    media: { type: 'string' },
    rate: { type: 'string', default: '0' },
    'https-port': { type: 'string' },
    'tls-cert': { type: 'string' },
    'tls-key': { type: 'string' },
    help: { type: 'boolean', short: 'h' },
  },
});

const CHUNK = 256 * 1024;
const ZEROS = Buffer.alloc(CHUNK + 16);
const LAST_MODIFIED = new Date(Date.UTC(2026, 10, 1)).toUTCString();

const state = {
  rate: Number(opts.rate) || 0,
  resetAfter: 0,
  resetCount: Infinity,
  failStatus: 0,
  failCount: 0,
  latencyMs: 0,
  stallAfter: 0,
  stallMs: 0,
  stallCount: 0,
  rangeShift: 0,
  rangeShiftCount: 0,
  failRules: [],
  variants: new Map(),
  log: [],
};

function resetState() {
  Object.assign(state, {
    rate: Number(opts.rate) || 0,
    resetAfter: 0,
    resetCount: Infinity,
    failStatus: 0,
    failCount: 0,
    latencyMs: 0,
    stallAfter: 0,
    stallMs: 0,
    stallCount: 0,
    rangeShift: 0,
    rangeShiftCount: 0,
    failRules: [],
  });
  state.variants.clear();
}

function parseSize(spec) {
  const match = /^(\d+(?:\.\d+)?)([kmg]?)$/i.exec(spec ?? '');
  if (!match) return null;
  const unit = { '': 1, k: 1024, m: 1024 ** 2, g: 1024 ** 3 }[match[2].toLowerCase()];
  return Math.floor(Number(match[1]) * unit);
}

function generated(sizeSpec, name, variant = 'a') {
  const size = parseSize(sizeSpec);
  if (size === null) return null;
  const key = createHash('sha256').update(`${name}:${variant}`).digest().subarray(0, 16);
  const etag = `"${createHash('sha1').update(`${sizeSpec}:${name}:${variant}`).digest('hex').slice(0, 20)}"`;
  return {
    size,
    etag,
    lastModified: LAST_MODIFIED,
    type: 'application/octet-stream',
    *chunks(start, end) {
      for (let offset = start; offset <= end;) {
        const length = Math.min(CHUNK, end - offset + 1);
        const skew = offset % 16;
        const iv = Buffer.alloc(16);
        iv.writeBigUInt64BE(BigInt(Math.floor(offset / 16)), 8);
        const cipher = createCipheriv('aes-128-ctr', key, iv);
        yield cipher.update(ZEROS.subarray(0, length + skew)).subarray(skew);
        offset += length;
      }
    },
  };
}

function mediaFile(dir, file) {
  const path = resolve(dir, file);
  if (!path.startsWith(resolve(dir))) return null;
  let stat;
  try {
    stat = statSync(path);
  } catch {
    return null;
  }
  if (!stat.isFile()) return null;
  const type = file.endsWith('.mp4')
    ? 'video/mp4'
    : file.endsWith('.mkv')
      ? 'video/x-matroska'
      : 'application/octet-stream';
  return {
    size: stat.size,
    etag: `"${stat.size.toString(16)}-${Math.floor(stat.mtimeMs).toString(16)}"`,
    lastModified: stat.mtime.toUTCString(),
    type,
    path,
  };
}

function resolveFile(pathname) {
  const parts = pathname.split('/').filter(Boolean).map(decodeURIComponent);
  if (parts[0] === 'f' && parts.length === 3) {
    return generated(parts[1], parts[2], state.variants.get(parts[2]) ?? 'a');
  }
  if (parts[0] === 'media' && parts.length === 2 && opts.media)
    return mediaFile(opts.media, parts[1]);
  return null;
}

function parseRange(header, size) {
  const match = /^bytes=(\d*)-(\d*)$/.exec(header?.trim() ?? '');
  if (!match) return null;
  let start;
  let end;
  if (match[1] === '') {
    const suffix = Number(match[2]);
    start = Math.max(0, size - suffix);
    end = size - 1;
  } else {
    start = Number(match[1]);
    end = match[2] === '' ? size - 1 : Math.min(Number(match[2]), size - 1);
  }
  if (start > end || start >= size) return 'unsatisfiable';
  return { start, end };
}

const sleep = (ms) => new Promise((done) => setTimeout(done, ms));

async function sendBody(req, res, file, start, end, rate, entry) {
  let sent = 0;
  const resetAfter = state.resetAfter > 0 && state.resetCount > 0 ? state.resetAfter : 0;
  if (resetAfter) state.resetCount -= 1;
  let stallAfter = state.stallAfter > 0 && state.stallCount > 0 ? state.stallAfter : 0;
  if (stallAfter) state.stallCount -= 1;
  const began = Date.now();
  let closed = false;
  res.on('close', () => (closed = true));
  const stream = file.path
    ? createReadStream(file.path, { start, end, highWaterMark: CHUNK })
    : null;
  const iterator = stream ? stream[Symbol.asyncIterator]() : file.chunks(start, end);
  try {
    while (!closed) {
      const next = await iterator.next();
      if (next.done) break;
      let chunk = next.value;
      if (resetAfter && sent + chunk.length >= resetAfter) {
        chunk = chunk.subarray(0, Math.max(0, resetAfter - sent));
        sent += chunk.length;
        entry.result = `reset after ${sent}`;
        await new Promise((done) => res.write(chunk, done));
        req.socket.destroy();
        return;
      }
      if (!res.write(chunk))
        await new Promise((done) => res.once('drain', done).once('close', done));
      sent += chunk.length;
      if (stallAfter && sent >= stallAfter) {
        stallAfter = 0;
        entry.stalled = sent;
        const until = Date.now() + state.stallMs;
        while (!closed && Date.now() < until) await sleep(50);
      }
      if (rate > 0) {
        const due = began + (sent / rate) * 1000;
        const wait = due - Date.now();
        if (wait > 0) await sleep(wait);
      }
    }
    if (closed) entry.result = `client closed after ${sent}`;
    else res.end();
  } finally {
    stream?.destroy();
    entry.bytes = sent;
  }
}

function retryAfterHeader(value) {
  if (!value || value === 'none') return {};
  if (value.startsWith('date:')) {
    return { 'Retry-After': new Date(Date.now() + Number(value.slice(5)) * 1000).toUTCString() };
  }
  return { 'Retry-After': value };
}

async function serveFile(req, res, url, entry) {
  const file = resolveFile(url.pathname);
  if (!file) {
    res.writeHead(404).end('not found');
    return 404;
  }
  if (state.latencyMs) await sleep(state.latencyMs);
  const rule = state.failRules.find(
    (item) =>
      item.count > 0 &&
      url.pathname.includes(item.name) &&
      (item.method === 'any' || item.method === req.method)
  );
  if (rule) {
    rule.count -= 1;
    res.writeHead(rule.status, retryAfterHeader(rule.retryAfter)).end(`simulated ${rule.status}`);
    return rule.status;
  }
  if (state.failStatus && state.failCount > 0) {
    state.failCount -= 1;
    res.writeHead(state.failStatus, { 'Retry-After': '1' }).end(`simulated ${state.failStatus}`);
    return state.failStatus;
  }
  const headers = {
    'Accept-Ranges': 'bytes',
    ETag: file.etag,
    'Last-Modified': file.lastModified,
    'Content-Type': file.type,
    'Cache-Control': 'no-store',
  };
  let range = req.headers.range ? parseRange(req.headers.range, file.size) : null;
  const ifRange = req.headers['if-range'];
  if (range && ifRange && ifRange !== file.etag && ifRange !== file.lastModified) {
    range = null;
    entry.ifRange = 'mismatch';
  }
  if (range === 'unsatisfiable') {
    res.writeHead(416, { ...headers, 'Content-Range': `bytes */${file.size}` }).end();
    return 416;
  }
  let start = range ? range.start : 0;
  if (range && state.rangeShift && state.rangeShiftCount > 0) {
    state.rangeShiftCount -= 1;
    start = Math.min(Math.max(0, start + state.rangeShift), file.size - 1);
    entry.rangeShifted = start;
  }
  const end = range ? range.end : file.size - 1;
  const status = range ? 206 : 200;
  res.writeHead(status, {
    ...headers,
    'Content-Length': String(end - start + 1),
    ...(range ? { 'Content-Range': `bytes ${start}-${end}/${file.size}` } : null),
  });
  if (req.method === 'HEAD') {
    res.end();
    return status;
  }
  const rate = Number(url.searchParams.get('rate') ?? state.rate) || 0;
  entry.status = status;
  await sendBody(req, res, file, start, end, rate, entry);
  return status;
}

async function sha256Of(pathname) {
  const file = resolveFile(pathname);
  if (!file) return null;
  const hash = createHash('sha256');
  if (file.path) {
    for await (const chunk of createReadStream(file.path, { highWaterMark: 4 * 1024 * 1024 }))
      hash.update(chunk);
  } else {
    for (const chunk of file.chunks(0, file.size - 1)) hash.update(chunk);
  }
  return { path: pathname, size: file.size, etag: file.etag, sha256: hash.digest('hex') };
}

function admin(url, res) {
  const q = url.searchParams;
  const json = (body) =>
    res.writeHead(200, { 'Content-Type': 'application/json' }).end(JSON.stringify(body, null, 2));
  switch (url.pathname) {
    case '/admin/config':
      for (const key of [
        'rate',
        'resetAfter',
        'failStatus',
        'failCount',
        'latencyMs',
        'stallAfter',
        'stallMs',
        'stallCount',
        'rangeShift',
        'rangeShiftCount',
      ]) {
        if (q.has(key)) state[key] = Number(q.get(key)) || 0;
      }
      if (q.has('resetCount')) state.resetCount = Number(q.get('resetCount')) || 0;
      else if (q.has('resetAfter')) state.resetCount = Infinity;
      return json({ ...state, variants: Object.fromEntries(state.variants), log: undefined });
    case '/admin/fail':
      state.failRules.push({
        name: q.get('name') ?? '',
        status: Number(q.get('status')) || 503,
        count: q.has('count') ? Number(q.get('count')) : 1,
        retryAfter: q.get('retryAfter') ?? 'none',
        method: (q.get('method') ?? 'any').toUpperCase().replace('ANY', 'any'),
      });
      return json(state.failRules);
    case '/admin/variant':
      state.variants.set(q.get('name') ?? '', q.get('variant') ?? 'a');
      return json(Object.fromEntries(state.variants));
    case '/admin/reset':
      resetState();
      return json({ ok: true });
    case '/admin/log':
      return json(state.log);
    case '/admin/sha256':
      return sha256Of(q.get('path') ?? '').then((result) =>
        result ? json(result) : res.writeHead(404).end('not found')
      );
    case '/':
    case '/admin':
      return res.writeHead(200, { 'Content-Type': 'text/plain' }).end(HELP);
    default:
      return res.writeHead(404).end('not found');
  }
}

function listMedia() {
  if (!opts.media) return [];
  return readdirSync(opts.media).filter((name) => /\.(mp4|mkv|mov|webm)$/.test(name));
}

async function main() {
  if (opts.help) {
    process.stdout.write(HELP);
    return;
  }
  if (positionals[0] === 'sha256') {
    const [, size, name, variant = 'a'] = positionals;
    state.variants.set(name, variant);
    console.log(JSON.stringify(await sha256Of(`/f/${size}/${name}`)));
    return;
  }
  const handle = (req, res) => {
    const url = new URL(req.url ?? '/', 'http://localhost');
    const entry = {
      at: new Date().toISOString(),
      method: req.method,
      path: url.pathname,
      range: req.headers.range,
      ifRange: req.headers['if-range'],
      ua: req.headers['user-agent'],
    };
    if (url.pathname === '/' || url.pathname.startsWith('/admin')) {
      admin(url, res);
      return;
    }
    state.log.push(entry);
    if (url.pathname === '/redirect') {
      res
        .writeHead(Number(url.searchParams.get('status')) || 302, {
          Location: url.searchParams.get('to') ?? '/',
        })
        .end();
      entry.status = 302;
      console.log(JSON.stringify(entry));
      return;
    }
    if (url.pathname === '/capture') {
      const body = JSON.stringify(req.headers);
      res
        .writeHead(200, { 'Content-Length': Buffer.byteLength(body), ETag: '"capture"' })
        .end(body);
      entry.status = 200;
      console.log(JSON.stringify(entry));
      return;
    }
    if (state.log.length > 300) state.log.shift();
    serveFile(req, res, url, entry)
      .then((status) => {
        entry.status = status;
        console.log(JSON.stringify(entry));
      })
      .catch((error) => {
        entry.error = String(error);
        console.log(JSON.stringify(entry));
        res.destroy();
      });
  };
  if (opts['https-port']) {
    const tls = { cert: readFileSync(opts['tls-cert']), key: readFileSync(opts['tls-key']) };
    createTlsServer(tls, handle).listen(Number(opts['https-port']), opts.host, () => {
      console.log(`download test server on https://${opts.host}:${opts['https-port']}`);
    });
  }
  const server = createServer(handle);
  server.listen(Number(opts.port), opts.host, () => {
    console.log(
      `download test server on http://${opts.host}:${opts.port} (Android emulator: http://10.0.2.2:${opts.port})`
    );
    for (const name of listMedia()) console.log(`  /media/${name}`);
  });
}

main();
